"""Extract selection as code (ADR 0076): the selected layers become one code layer that draws the same.

The selected layers - with their clips, keys and lifetimes - are cut out as a small project of their own, its
times moved so the code layer's clock starts at 0, and written by the readable Python export (ADR 0031) as
one Manim scene. That scene is the new code layer's code; the layer starts where the selection did (on the
frame grid, so the scene's frames fall on the project's) and ends where it ended, in the selection's place
in the stack. One edit, so one undo step brings the layers back.

Nothing partial is offered: when the readable export cannot reproduce the selection (a camera, a pinned
label, a smart morph, a part...), or the rest of the project uses one of the selected layers, or the selection
uses a layer that is not selected, ``extract_as_code`` raises ``EditError`` with every reason.
"""

from __future__ import annotations

import math
from collections.abc import Iterable
from dataclasses import dataclass

from pydantic import ValidationError

from ..code import helpers
from ..editing import edits
from ..editing.edits import Edit, EditError
from ..model.schema import PYTHON_TYPES, Layer, Lifetime, Project, Spec
from . import python_export

_READABLE_HEADER = '"""Generated by Manim Studio (readable form: plain Manim, ADR 0031)."""'
_HEADER = (
    '"""Extracted from Manim Studio layers (ADR 0076).\n\n'
    "Plain Manim code that draws what the layers drew; the editor sets the frame size, the frame rate\n"
    'and the background, and plays this scene from the code layer\'s start. Edit it freely.\n"""'
)


@dataclass(frozen=True)
class Extraction:
    edit: Edit
    layer_id: str  # the new code layer
    code: str  # its code
    # The code of the Python objects and helpers the new code embeds (ADR 0051, 0058): the editor may trust
    # the new code only when every one of these was trusted already.
    embedded: tuple[str, ...] = ()


def extract_as_code(project: Project, layer_ids: Iterable[str]) -> Extraction:
    """The layers ``layer_ids`` (and their parts) replaced by one code layer drawing the same, as one edit;
    raises ``EditError`` saying every reason when it cannot be done exactly."""
    picked = list(dict.fromkeys(layer_ids))
    if not picked:
        raise EditError("select the objects to turn into code")
    known = {x.id: x for x in project.layers}
    for layer_id in picked:
        if layer_id not in known:
            raise EditError(f"no layer {layer_id!r}")
    chosen = set(picked)
    for layer_id in picked:
        chosen |= {x.id for x in project.descendants(layer_id)}
    problems: list[str] = []
    if not project.camera.is_default:  # ADR 0048: the code layer would be seen through it twice
        problems.append("the project's camera is turned: a code layer is a flat picture of its scene")
    problems += _stack_problems(project, chosen)
    removed = edits.remove_layers(project, [i for i in picked if known[i].parent_id not in chosen])
    problems += _user_problems(project, removed.project, chosen)
    fps = project.canvas.fps
    start, end = _span(project, chosen)
    start = math.floor(start * fps + 1e-6) / fps  # on the frame grid: the scene's frames are the project's
    duration = (end if math.isfinite(end) else project.canvas.duration) - start
    sub = None
    try:
        sub = Project.model_validate(
            {
                "canvas": project.canvas.model_copy(update={"duration": max(duration, 1 / fps)}),
                "layers": _shifted([x for x in project.layers if x.id in chosen], -start),
                "helpers": project.helpers,
                "morph_matching": project.morph_matching,
            }
        )
    except ValidationError as error:  # it refers to a layer that is not selected
        message = str(error.errors()[0]["msg"]).removeprefix("Value error, ")
        problems.append(f"it uses a layer that is not selected ({message}): select that one too")
    if sub is not None:
        problems += python_export.readable_problems(sub)
    if problems:
        raise EditError("; ".join(dict.fromkeys(problems)))
    assert sub is not None
    labels = [known[i].label for i in picked]
    scene = python_export.class_name(f"{labels[0]} scene" if len(labels) == 1 else "extracted scene")
    if scene in python_export.RESERVED:
        scene = "ExtractedScene"
    code = _layer_code(python_export.to_python(sub, scene).code, labels)
    index = sum(1 for x in project.layers[: _first_index(project, chosen)] if x.id not in chosen)
    layer_id = edits.new_layer_id(removed.project, "Code")
    name = f"{labels[0]} (code)" if len(labels) == 1 else "Extracted code"
    added = edits.add_layer(
        removed.project, Spec(type="Code", params={"code": code}), index=index, name=name, layer_id=layer_id
    )
    lifetime = Lifetime(in_=start, out=end if math.isfinite(end) else None)
    final = edits.update_layer(added.project, layer_id, lifetime=lifetime).project
    kind, touched = edits.classify(project, final)
    return Extraction(Edit(final, kind, touched), layer_id, code, _embedded(sub))


def _stack_problems(project: Project, chosen: set[str]) -> list[str]:
    """A layer drawn between selected ones would end up under or over all of them."""
    places = [i for i, x in enumerate(project.layers) if x.id in chosen]
    between = [x for x in project.layers[places[0] : places[-1] + 1] if x.id not in chosen]
    return [
        f"{x.label}: it is drawn between the selected layers; select it too or move it above or below them"
        for x in between
        if x.parent_id is None or x.parent_id not in chosen
    ]


def _user_problems(project: Project, remaining: Project, chosen: set[str]) -> list[str]:
    """Layers outside the selection that deleting it would delete or change: they use a selected layer
    (a morph into it, a path, a connector, a trace, a pin, a group...)."""
    kept = {x.id: x for x in remaining.layers}
    out = []
    for layer in project.layers:
        if layer.id in chosen:
            continue
        if kept.get(layer.id) != layer:
            out.append(f"{layer.label}: it uses a selected layer; select it too")
    return out


def _span(project: Project, chosen: set[str]) -> tuple[float, float]:
    """When the selection starts (its first appearance, clip or key) and ends (its last disappearance)."""
    starts, ends = [], []
    for layer in project.layers:
        if layer.id not in chosen:
            continue
        begin, finish = project.lifetime(layer.id)
        starts += [begin, *(c.start for c in layer.clips), *(k.t for t in layer.tracks.values() for k in t)]
        ends.append(finish)
    return max(0.0, min(starts)), max(ends)


def _shifted(layers: list[Layer], dt: float) -> list[Layer]:
    """``layers`` with every time (clip starts, keys, explicit lifetimes) moved by ``dt``."""
    out = []
    for layer in layers:
        data = layer.model_dump(by_alias=True)
        for clip in data["clips"]:
            clip["start"] = max(0.0, round(clip["start"] + dt, 9))
        for track in data["tracks"].values():
            for key in track:
                key["t"] = max(0.0, round(key["t"] + dt, 9))
        for end in ("in", "out"):
            if data["lifetime"][end] is not None:
                data["lifetime"][end] = max(0.0, round(data["lifetime"][end] + dt, 9))
        out.append(data)
    return out


def _first_index(project: Project, chosen: set[str]) -> int:
    return next(i for i, x in enumerate(project.layers) if x.id in chosen)


def _layer_code(code: str, labels: list[str]) -> str:
    """The readable file as a code layer's code: its own header, no ``config`` lines (the editor renders a
    code layer at the project's size, rate and a transparent background)."""
    lines = [line for line in code.splitlines() if not line.startswith("config.")]
    text = "\n".join(lines).replace(_READABLE_HEADER, _HEADER, 1)
    names = "\n".join(f"#   - {' '.join(label.split())}" for label in labels)
    text = text.replace("\nfrom __future__", f"\n# Layers:\n{names}\n\nfrom __future__", 1)
    while "\n\n\n\n" in text:
        text = text.replace("\n\n\n\n", "\n\n\n")
    compile(text, "<extracted>", "exec")  # never a broken layer
    return text.rstrip() + "\n"


def _embedded(sub: Project) -> tuple[str, ...]:
    """The Python objects' code and the helpers it imports, as the readable file embeds them."""
    out: list[str] = []
    for layer in sub.layers:
        if layer.spec is not None and layer.spec.type in PYTHON_TYPES:
            code = str(layer.spec.params.get("code", ""))
            out += [code, *(sub.helper(name).code for name in helpers.needed(sub, code))]
    return tuple(dict.fromkeys(out))
