class SmartScene(m.Scene):
    """A Scene with ``smart_transform(source, target)``: ``source`` is replaced by ``target``."""

    def smart_transform(self, source: m.Mobject, target: m.Mobject, **kwargs) -> None:
        animation, start, end = smart_transform(source, target, **kwargs)
        if start is not source:
            self.remove(source)
            self.add(start)
        self.play(animation)
        if end is not target:
            self.remove(end)  # its drawing is exactly the target's (the last frame is exact)
            self.add(target)


