"""Generate docs/guide/shortcuts.md from the editor itself.

The table is read the same way Help > Keyboard Shortcuts (F1) reads it
(``ui/shortcuts_help.py``): every menu item that has a shortcut, the panels' actions that
have one, and the fixed list of mouse gestures (``GESTURES``). A few keys are bound with a
bare ``QShortcut`` or an action without a name, which the dialog cannot list; they are in
``EXTRA`` below - keep it in step with the code it names.

The window is built offscreen with every user folder redirected to a temporary folder, no
build worker, no preview process, no sound and no plugins, so the output depends only on the
code: run it again and nothing changes unless a shortcut did.

    python scripts/gen_shortcuts.py                          # print the Markdown
    python scripts/gen_shortcuts.py -o docs/guide/shortcuts.md
"""

from __future__ import annotations

import argparse
import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# (area, what, keys): keys bound without a named QAction, so F1 cannot read them.
EXTRA: tuple[tuple[str, str, str], ...] = (
    ("Transport", "Step one frame back, forward", "Left, Right"),  # ui/main_window.py, unnamed actions
    ("Code page", "Run the code in the editor (apply it as one undo step)", "Ctrl+Enter"),  # pages/code.py
    ("Code page", "Rename the chosen code layer or Python object", "F2"),  # pages/code.py QShortcut
    ("Code page", "Delete the chosen code layer or Python object", "Delete"),  # pages/code.py QShortcut
    ("Properties", "Apply a multi-line field (LaTeX, code)", "Ctrl+Enter"),  # ui/fields.py
    ("Animate gestures", "Frame every key (the graph has the focus)", "F"),  # ui/graph_editor.py
)

HEADER = """# Keyboard shortcuts and mouse gestures

<!-- Generated by scripts/gen_shortcuts.py - do not edit by hand. Regenerate with:
     python scripts/gen_shortcuts.py -o docs/guide/shortcuts.md -->

Everything here is also in the editor: **Help > Keyboard Shortcuts...** (F1) shows the same
table with a search field. Keys are written as on Windows; Ctrl is Cmd on macOS.

"""

FOOTER = """## See also

- [The editor](the-editor.md) - the pages and panels these keys work in
- [Animation](animation.md) - clips, keys, the timeline and the graph
- [Objects](objects.md) - what the canvas gestures act on
- [User guide index](index.md)
"""


def _isolate(tmp: Path) -> None:
    """Point every user folder at ``tmp`` and switch off the helper processes (as the tests do)."""
    os.environ["QT_QPA_PLATFORM"] = "offscreen"
    for name, sub in (
        ("MANIM_STUDIO_SETTINGS", "settings/manim-studio.ini"),
        ("MANIM_STUDIO_PLUGINS", "plugins"),
        ("MANIM_STUDIO_LIBRARY", "library"),
        ("MANIM_STUDIO_RECOVERY", "recovery"),
        ("MANIM_STUDIO_LOG_DIR", "logs"),
        ("MANIM_STUDIO_TRUST_FILE", "trusted-code.json"),
        ("MANIM_STUDIO_CACHE", "cache"),
    ):
        os.environ[name] = str(tmp / sub)
    for name in ("MANIM_STUDIO_WORKER", "MANIM_STUDIO_PREVIEW", "MANIM_STUDIO_CODE", "MANIM_STUDIO_AUDIO"):
        os.environ[name] = "0"
    (tmp / "plugins").mkdir(parents=True, exist_ok=True)


Row = tuple[str, str, str, bool]  # (where, what, keys, keys are key names rather than words)


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _keys(text: str) -> str:
    return ", ".join(f"`{key.strip()}`" for key in text.split(", ") if key.strip())


def _described(action) -> str:
    """A panel action's tooltip without its "(keys)" tail, else its text: "Up" says less than
    "Bring forward"."""
    from manim_studio.ui import shortcuts_help

    text = shortcuts_help._plain(action.text())
    tips = [action.toolTip()] + [w.toolTip() for w in action.associatedObjects() if hasattr(w, "toolTip")]
    for tip in tips:  # the button showing the action carries the tooltip (ui/layers_panel.py)
        tip = tip.split(" (")[0].strip()
        if tip and tip != text:
            return f"{tip} ({text})"
    return text


def collect() -> list[Row]:
    """Every row: menus (in menu order), panel actions, gestures, then ``EXTRA``."""
    from PySide6.QtGui import QAction, QKeySequence
    from PySide6.QtWidgets import QApplication

    from manim_studio.ui import shortcuts_help, theme
    from manim_studio.ui.main_window import MainWindow

    app = QApplication.instance() or QApplication([])
    theme.apply(app)
    window = MainWindow()
    plain = shortcuts_help._plain

    def keys_of(action: QAction) -> str:  # portable text: the same on every platform
        return ", ".join(k.toString(QKeySequence.SequenceFormat.PortableText) for k in action.shortcuts())

    def menu_rows(menu, path: str) -> list[Row]:  # as shortcuts_help._menu_rows
        out: list[Row] = []
        for action in menu.actions():
            if action.isSeparator():
                continue
            if action.menu() is not None:
                out += menu_rows(action.menu(), f"{path} > {plain(action.text())}")
            elif action.shortcuts():
                out.append((f"{path} menu", plain(action.text()), keys_of(action), True))
        return out

    try:
        rows: list[Row] = []
        for top in window.menuBar().actions():
            if top.menu() is not None:
                rows += menu_rows(top.menu(), plain(top.text()))
        seen = {(what, keys) for _area, what, keys, _k in rows}
        panels: list[Row] = []
        for action in window.findChildren(QAction):  # as keyboard_rows does, sorted for stability
            if not action.shortcuts() or not action.text():
                continue
            keys = keys_of(action)
            if (plain(action.text()), keys) not in seen:
                seen.add((plain(action.text()), keys))
                panels.append(("Panels", _described(action), keys, True))
        rows += sorted(panels)
        rows += [(f"{row.area} gestures", row.what, row.keys, False) for row in shortcuts_help.GESTURES]
        rows += [(area, what, keys, True) for area, what, keys in EXTRA]
        return rows
    finally:
        window.close()
        window.deleteLater()


def render(rows: list[Row]) -> str:
    """The Markdown page: one table per area, in the order the areas first appear."""
    areas: dict[str, list[tuple[str, str]]] = {}
    for area, what, keys, named in rows:
        top, _, sub = area.partition(" > ")
        if sub:  # "View > Pages menu": a submenu's items under their menu, prefixed
            top, sub = f"{top} menu", sub.removesuffix(" menu")
        label = f"{sub} > {what}" if sub else what
        areas.setdefault(top, []).append((label, _keys(keys) if named else keys))
    out = [HEADER]
    for area, items in areas.items():
        out.append(f"## {area}\n\n| what | keys |\n|---|---|\n")
        out.extend(f"| {_cell(what)} | {_cell(keys)} |\n" for what, keys in items)
        out.append("\n")
    out.append(FOOTER)
    return "".join(out).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("-o", "--output", type=Path, help="write the page here (UTF-8, LF), not to stdout")
    args = parser.parse_args(argv)
    tmp = Path(tempfile.mkdtemp(prefix="manim-studio-shortcuts-"))
    try:
        _isolate(tmp)
        sys.path.insert(0, str(ROOT / "src"))
        text = render(collect())
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    if args.output:
        args.output.write_text(text, encoding="utf-8", newline="\n")
    else:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
